from __future__ import annotations

import yaml

from legacy2mcp.config import Legacy2McpConfig
from legacy2mcp.discovery.classify import build_config
from legacy2mcp.discovery.generate import render_yaml
from legacy2mcp.discovery.scan import DbFinding, DbTableFinding, RouteFinding, RouteParam, ScanResult, SoapFinding


def test_soap_finding_produces_soap_config():
    scan = ScanResult(soap=SoapFinding(wsdl_url="https://svc.example.com/Legacy?wsdl", file="client.py"))
    config, todos = build_config(scan)

    assert config["adapters"][0]["type"] == "soap"
    assert config["adapters"][0]["config"]["wsdl_url"] == "https://svc.example.com/Legacy?wsdl"
    assert config["adapters"][0]["config"]["allow_write_operations"] is False
    Legacy2McpConfig.model_validate(config)  # must be a loadable config


def test_soap_finding_without_literal_url_adds_todo():
    scan = ScanResult(soap=SoapFinding(wsdl_url=None, file="client.py"))
    config, todos = build_config(scan)

    assert config["adapters"][0]["config"]["wsdl_url"] == "REPLACE_ME_WSDL_URL"
    assert any("wsdl_url" in t for t in todos)


def test_db_finding_produces_db_config():
    scan = ScanResult(
        db=DbFinding(dialect="postgres", tables=[DbTableFinding(table="orders", columns=["id", "status"], file="models.py")])
    )
    config, todos = build_config(scan)

    adapter_config = config["adapters"][0]["config"]
    assert config["adapters"][0]["type"] == "db"
    assert adapter_config["dialect"] == "postgres"
    assert adapter_config["tables"][0]["name"] == "orders"
    assert adapter_config["tables"][0]["operations"] == ["select"]
    Legacy2McpConfig.model_validate(config)


def test_routes_produce_rest_config_with_write_gating():
    scan = ScanResult(
        routes=[
            RouteFinding(name="get_order", method="GET", path="/orders/{id}", description="", params=[]),
            RouteFinding(name="create_order", method="POST", path="/orders", description="", params=[]),
        ]
    )
    config, todos = build_config(scan)

    adapter_config = config["adapters"][0]["config"]
    assert config["adapters"][0]["type"] == "rest"
    by_name = {e["name"]: e for e in adapter_config["endpoints"]}
    assert by_name["get_order"]["write"] is False
    assert by_name["create_order"]["write"] is True
    assert adapter_config["allow_write_operations"] is False
    Legacy2McpConfig.model_validate(config)


def test_no_findings_produces_scaffold_with_todo():
    config, todos = build_config(ScanResult())

    assert config["adapters"][0]["type"] == "rest"
    assert config["adapters"][0]["config"]["endpoints"] == []
    assert todos


def test_render_yaml_is_valid_yaml_with_header_comment():
    config, todos = build_config(ScanResult(db=DbFinding(dialect=None, tables=[DbTableFinding("orders", ["id"], "m.py")])))
    text = render_yaml(config, "repo", todos)

    assert text.startswith("# Generated by `legacy2mcp init`")
    assert "TODO" in text
    parsed = yaml.safe_load(text)
    assert parsed == config
