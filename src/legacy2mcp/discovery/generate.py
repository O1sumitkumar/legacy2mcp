"""
Render a `classify.build_config()` result to a config.yaml, with a header
comment block (generated-by, source, TODOs) -- PyYAML can't attach comments
to a dumped dict, so this writes the header as plain text above the dump
rather than trying to splice comments into the YAML tree.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import yaml

from legacy2mcp.discovery.contract import LegacyInterfaceContract


def render_yaml(config: dict, source_label: str, todos: list[str]) -> str:
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Generated by `legacy2mcp init`",
        f"# Source: {source_label}",
        f"# Generated: {generated_at}",
        "#",
        "# Review before running -- this was built from a static scan, a reviewed",
        "# contract, or an OpenAPI/Swagger spec, not a live schema, so nothing here",
        "# is verified the way SOAP/DB config is once `legacy2mcp run` actually",
        "# introspects the WSDL/database.",
    ]
    if todos:
        lines.append("#")
        lines.append("# TODO:")
        for todo in todos:
            lines.append(f"#   - {todo}")
    lines.append("")

    body = yaml.safe_dump(config, sort_keys=False, default_flow_style=False)
    return "\n".join(lines) + body


def render_contract_yaml(contract: LegacyInterfaceContract, source_label: str) -> str:
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    by_confidence: dict[str, int] = {}
    needs_review_count = 0
    for op in contract.operations:
        by_confidence[op.confidence] = by_confidence.get(op.confidence, 0) + 1
        if op.needs_review:
            needs_review_count += 1

    lines = [
        "# Generated by `legacy2mcp discover`",
        f"# Source: {source_label}",
        f"# Generated: {generated_at}",
        "#",
        f"# {len(contract.operations)} operation(s) found -- "
        + ", ".join(f"{count} {level}-confidence" for level, count in sorted(by_confidence.items()))
        + f", {needs_review_count} flagged for review.",
        "#",
        "# Review every operation below before running",
        "# `legacy2mcp init --from-contract <this file> --out config.yaml`.",
        "# Nothing here is verified against a live backend -- confidence reflects how",
        "# the finding was made (a live schema/catalog vs. a curated artifact vs.",
        "# inferred from sampled traffic), not whether it's correct.",
        "",
    ]
    body = yaml.safe_dump(contract.model_dump(), sort_keys=False, default_flow_style=False)
    return "\n".join(lines) + body


def write_config(path: str | Path, text: str) -> Path:
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return out
